function w = mvst_texdata(filename)
%MVST_TEXDATA  Writer for LaTeX data macros (gains, costs, systems).
%   W = MVST_TEXDATA(FILENAME) opens FILENAME and returns a struct W of
%   function handles for emitting LaTeX \newcommand definitions, so that
%   numerical values computed in MATLAB can be transferred to the document
%   dynamically (via \input{FILENAME} in LaTeX).
%
%     W.mat(name, M [,prec])  % \newcommand{\name}{\begin{bmatrix}...}}
%     W.num(name, x [,prec])  % \newcommand{\name}{<formatted scalar>}
%     W.raw(name, str)        % \newcommand{\name}{<verbatim string>}
%     W.close()              % close the file
%
%   Macro NAME must be letters only (TeX control-sequence rule); use words
%   for indices, e.g. 'KmjlsInfModeOne'.
%
%   See also MVST_FMTMAT, MVST_SAVEPDF.
if ~(ischar(filename) || (isstring(filename) && isscalar(filename))) ...
        || strlength(string(filename)) == 0
    error('mvst:texdata:filename', 'FILENAME must be a non-empty path string.');
end
filename = char(filename);
d = fileparts(filename);
if ~isempty(d) && ~exist(d,'dir'); mkdir(d); end
fid = fopen(filename, 'w');
if fid < 0; error('mvst:texdata:open','Cannot open %s', filename); end
fprintf(fid, '%% Auto-generated by the mvst example scripts. Do not edit.\n');

w.mat   = @(name,M,varargin) emit(fid, name, mvst_fmtmat(M, optprec(varargin)));
w.num   = @(name,x,varargin) emit(fid, name, mvst_fmtmat(x, optprec(varargin)));
w.raw   = @(name,str)        emit(fid, name, str);
w.close = @() fclose(fid);
end

function emit(fid, name, body)
assert(all(isletter(name)), 'mvst:texdata:name', ...
    'Macro name "%s" must contain letters only.', name);
% \def (not \newcommand) so the document may pre-declare fallbacks that this
% file then overrides via \input, without a "command already defined" error.
% Use fwrite, NOT fprintf('%s',...): fprintf collapses the '\\' row
% separators in the bmatrix body (escape processing), which would flatten
% every matrix into a single row.
fwrite(fid, ['\def\' name '{' body '}' newline]);
end

function p = optprec(v)
if isempty(v); p = 3; else; p = v{1}; end
end
