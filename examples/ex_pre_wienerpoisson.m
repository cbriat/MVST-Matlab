function ex_pre_wienerpoisson()
%EX_PRE_WIENERPOISSON  The two continuous noise mechanisms of the general
%  impulsive class of Chapter 2 (preliminaries, Section sec:pre:cov:imp,
%  flow eq:pre:cov:imp:flowsde), figure fig:pre:wienerpoisson.
%
%  SYSTEM.  Scalar instance of the flow eq:pre:cov:imp:flowsde with one
%  Brownian channel and one Poissonian channel, no input, no impulse times:
%      dx = a x dt + sigma x dW + (j-1) x d(eta),   x(0) = x0,
%  with W a standard Wiener process and eta a Poisson process of intensity
%  lambda, independent of W.  At each arrival of eta the state is reset
%  within the flow, x -> j x.
%
%  SIMULATION.  Euler-Maruyama on [0,T] with step dt, using
%      dW ~ N(0,dt),   d(eta) = 1 with probability lambda*dt, else 0,
%  and the SAME realizations of W and eta in the three panels:
%   (a) the Wiener path W(t);
%   (b) the compensated Poisson path eta(t) - lambda t;
%   (c) the state x(t) driven by both (logarithmic vertical axis, so that
%       every reset x -> j x appears as the same downward step log(j) and
%       the diffusion stays visible after the state has decayed).
%
%  DATA MACROS (figures/data/pre_wienerpoisson.tex): the intensity lambda
%  and the realized number of Poisson arrivals on [0,T], both printed in
%  the caption.

here = fileparts(mfilename('fullpath'));
root = fullfile(here,'..');
% requires mvst_setup (library and solvers on the path)
mvst_latexdefaults(); gc = mvst_gemcolors();
figdir = mvst_figdir();
datdir = fullfile(figdir,'data');

% ------------------------------------------------------------- parameters
a = -0.5; sigma = 0.4; j = 0.6; lambda = 1; x0 = 1;
T = 10; dt = 1e-3; nt = round(T/dt)+1; t = (0:nt-1)*dt;

% ------------------------------------------------ Euler-Maruyama simulation
rng(7);
dW   = sqrt(dt)*randn(1,nt-1);
dEta = double(rand(1,nt-1) < lambda*dt);
W    = [0, cumsum(dW)];
Eta  = [0, cumsum(dEta)];
x    = zeros(1,nt); x(1) = x0;
for k = 1:nt-1
    x(k+1) = x(k) + a*x(k)*dt + sigma*x(k)*dW(k) + (j-1)*x(k)*dEta(k);
end
assert(all(x > 0), 'state left the positive half-line (step too large)');
njumps = Eta(end);
tjump  = t([false, dEta > 0]);
fprintf('a = %.2f, sigma = %.2f, j = %.2f, lambda = %.2f, x0 = %.2f, T = %g, dt = %g\n', ...
        a, sigma, j, lambda, x0, T, dt);
fprintf('realized Poisson arrivals on [0,%g]: %d  at t = %s\n', T, njumps, mat2str(tjump,3));
fprintf('x(T) = %.4e\n', x(end));

% ------------------------------------------- figure: three stacked panels
% Stacked vertically at full width (no half-width tiling).  Decimate for
% plotting only, keeping both samples around every arrival so that the
% resets are drawn as vertical drops.
keep = false(1,nt); keep(1:10:nt) = true; keep(end) = true;
ij = find([false, dEta > 0]); keep(ij) = true; keep(max(ij-1,1)) = true;
d = find(keep);

fig = figure('Color','w','Units','centimeters','Position',[2 2 14 14]);
tl  = tiledlayout(fig, 3, 1, 'TileSpacing','compact', 'Padding','compact');

ax1 = nexttile(tl); hold(ax1,'on'); grid(ax1,'on'); box(ax1,'on');
plot(ax1, t(d), W(d), '-', 'Color', gc.sapphire, 'LineWidth', 1.0);
ylabel(ax1, '$W(t)$', 'Interpreter','latex');

ax2 = nexttile(tl); hold(ax2,'on'); grid(ax2,'on'); box(ax2,'on');
plot(ax2, t(d), Eta(d) - lambda*t(d), '-', 'Color', gc.ruby, 'LineWidth', 1.0);
ylabel(ax2, '$\eta(t)-\lambda t$', 'Interpreter','latex');

ax3 = nexttile(tl); hold(ax3,'on'); grid(ax3,'on'); box(ax3,'on');
for tk = tjump
    xline(ax3, tk, ':', 'Color', [.55 .55 .55], 'LineWidth', 0.8);
end
plot(ax3, t(d), x(d), '-', 'Color', gc.topaz, 'LineWidth', 1.2);
set(ax3, 'YScale', 'log');
ylabel(ax3, '$x(t)$', 'Interpreter','latex');
xlabel(ax3, '$t$', 'Interpreter','latex');

% vertical padding so that no curve touches the axes frame
pad = @(v) [min(v) max(v)] + 0.08*(max(v)-min(v))*[-1 1];
ylim(ax1, pad(W));
ylim(ax2, pad(Eta - lambda*t));
lx = pad(log10(x));
ylim(ax3, 10.^lx);
set(ax3, 'YTick', 10.^(floor(lx(1)):2:ceil(lx(2))), 'YMinorGrid', 'off');
set([ax1 ax2 ax3], 'FontSize', 11, 'XLim', [0 T]);
set([ax1 ax2], 'XTickLabel', []);
linkaxes([ax1 ax2 ax3], 'x');
mvst_savepdf(fig, fullfile(figdir,'pre_wienerpoisson_combined.pdf'));
fprintf('  wrote pre_wienerpoisson_combined.pdf\n');

% ------------------------------------------------------------ data macros
if ~exist(datdir,'dir'); mkdir(datdir); end
fid = fopen(fullfile(datdir,'pre_wienerpoisson.tex'),'w');
fprintf(fid,'%% Auto-generated by the mvst example scripts. Do not edit.\n');
fprintf(fid,'\\def\\PreWPlam{%g}\n', lambda);
fprintf(fid,'\\def\\PreWPnjumps{%d}\n', njumps);
fclose(fid);
fprintf('  wrote data/pre_wienerpoisson.tex\n');
end
